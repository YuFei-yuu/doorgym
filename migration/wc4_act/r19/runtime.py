"""Future execution binding. R13 engineering run never creates a training order."""
import json,hashlib,os
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
SUPPORT=ROOT/'migration/wc4_act'
DATA=ROOT/'.repro/runs/wc4-fulltask-reaudit-r11-20261021/lerobot/local/wc4_fulltask_reaudit_r11_20261021'
REPO='local/wc4_fulltask_reaudit_r11_20261021'
R12=ROOT/'.repro/runs/wc4-fulltask-act-r12-s1000-20261022'

def read(p):return json.loads(Path(p).read_text())
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def write(p,x):Path(p).write_text(json.dumps(x,indent=2,ensure_ascii=False)+'\n')

def training_argv(run):
    import sys
    from commands import build
    cmd=build('train',Path(run).name,gpu=0,seed=1000,train_steps=75000)['argv']
    cmd=[sys.executable,'-B',str(SUPPORT/'r19/train.py'),*cmd[2:]]
    return [('--dataset.repo_id='+REPO if x.startswith('--dataset.repo_id=') else
        '--dataset.root='+str(DATA) if x.startswith('--dataset.root=') else
        '--output_dir='+str(Path(run)/'train') if x.startswith('--output_dir=') else x) for x in cmd]


def authorized_run():
    # A future task must explicitly establish a unique run and its budget/order.
    # No such order is generated by R13 or accepted from a default environment.
    run=Path(os.environ['WC4_EXECUTION_RUN']).resolve()
    if run==R12 or run.name=='wc4-engineering-r13-20261022':raise RuntimeError('Protected historical/engineering directory')
    order=read(run/'TRAINING_ORDER.json')
    if not order.get('authorized_by_new_user_task') or not order.get('r12_consumed_budget_acknowledged'):raise RuntimeError('Missing later task/budget authorization')
    if order['seed']!=1000 or order['steps']!=75000:raise RuntimeError('Original recipe changed')
    assert order['start_update']==50000 and order['new_optimizer_updates']==25000 and order['evaluation_budget']==16
    assert order['diagnostic_seeds']==list(range(62200,62216))
    verify_run(run)
    if order.get('resume_checkpoint'):validate_checkpoint(Path(order['resume_checkpoint']))
    return run,order


def verify_run(run):
    for name,digest in read(Path(run)/'source-binding.json').items():
        if sha(ROOT/name)!=digest:raise RuntimeError('Execution source changed: '+name)
    for name,digest in read(Path(run)/'frozen-files.json').items():
        if sha(Path(run)/name)!=digest:raise RuntimeError('Frozen execution parameters changed: '+name)
    if __import__('shutil').disk_usage(ROOT).free<40*1024**3:raise RuntimeError('Capacity stop')
    if read(DATA/'meta/info.json')['total_frames']!=159529:raise RuntimeError('Dataset changed')


def validate_checkpoint(directory):
    directory=Path(directory)
    if (directory/'COMMITTED.json').exists():
        manifest=read(directory/'COMMITTED.json')
        for name,digest in manifest['files'].items():
            if sha(directory/name)!=digest:raise RuntimeError('Corrupt stopped checkpoint: '+name)
        step=manifest['step']
    else:
        order=read(Path(os.environ['WC4_EXECUTION_RUN'])/'TRAINING_ORDER.json')
        if str(directory)!=order['resume_checkpoint']:raise RuntimeError('Unbound resume checkpoint')
        for name,entry in order['resume_state_files'].items():
            if sha(directory/name)!=entry['sha256']:raise RuntimeError('Corrupt R15 resume state: '+name)
        step=50000
    if read(directory/'training_state/training_step.json')['step']!=step:raise RuntimeError('Checkpoint boundary mismatch')
    return step
